"""R-126 G4 mass rollup (Arbiter). Light box script: itemises the ruled chain R-031 -> R-125,
cross-checks lines against CAD STEP volumes (CadQuery, 7075 2810 kg/m3) and the fastener BOMs.
Outputs mass_rollup_g4.json. Re-run: python3 modules/arbiter/g4_rollup.py (from repo root)."""
import json, os
R='modules/'
off=json.load(open(R+'arbiter/mass_rollup_official.json'))
fa=json.load(open(R+'actuators/results/fastener_bom.json'))['totals']
cm=json.load(open(R+'actuators/results/cad_mass.json'))
RHO=2810e-6  # kg per cm3
# CAD volumes measured with CadQuery on this commit (cm3); see /tmp/stepvol.py method in MASS_ROLLUP_G4.md
VOL={'knee_twin_housing':108.515,'knee_twin_housing_release_r116':143.034,'standoff_r14':41.911,
     'housing_7013_real_coaxX':71.675,'palm_7075':42.517,'hip_pitch_lever_r031_mw_b30_d36_RC':155.055}
L=[]
def add(mod,line,kg,tag,src,note=''): L.append(dict(module=mod,line=line,kg=round(kg,3),tag=tag,source=src,note=note))
# 1. R-031 official itemised base (credible column), kept line by line
for x in off['lines']:
    add('base R-031',x['line'],x['credible_kg'],'RULED (R-022..R-031 evidence)',x.get('source',''))
# 2. post-R-031 ruled chain (no itemised ledger existed; buckets reconstructed from RULINGS.md reserve trail)
chain=[('R-032..R-045','torso 5.026 line (R-035), P-027 wrist -1.332 (R-035), D69 knee rev B, spreaders, hip lever L47 +0.43 (R-056/R-069) etc.; net per RULINGS reserve trail 0.691->0.32',0.371),
       ('R-046..R-079','covers/vents, harness mass-down, pad cores, touch protection; reserve 0.32 -> -0.13',0.450),
       ('R-080..R-116','chest backing, trunnion bushes L61/L62, R-099 +0.166, R-116 +0.008; reserve -0.13 -> -0.64',0.510),
       ('R-120','CRBH 7013 + housing + stand-off + pad (net)',0.194),('R-121','R13 flange/stand-off',0.059),
       ('R-123 (c)','leg actuator fasteners 0.819 counted - 0.302 booked',0.517),('R-123 (d)','stand-off R11',0.060),
       ('R-125 (a)','W2 stand-off +0.044, wrap carrier +0.140 [EST full]',0.184),('R-125 (a2)','arm-structure fasteners 0.500 - 0.107 overlap',0.393),
       ('R-125 row 13','Ti non-structural arm screws (half credit)',-0.011),('R-125 (c)','arm/waist actuator fasteners 1.265 - 0.39',0.875)]
for r,l,kg in chain: add('ruled chain',r+': '+l,kg,'RULED',r)
ledger=sum(x['kg'] for x in L)
# 3. G4 CAD / BOM cross-checks
fin_cad=(VOL['knee_twin_housing_release_r116']-VOL['knee_twin_housing'])*RHO   # fins + R-116 boss, per knee
adj=[]
adj.append(('knee fins rev B: CAD %.4f/knee (incl. R-116 boss) vs booked 0.090 EST + 0.004 boss'%fin_cad, 2*(fin_cad-0.094),'CAD-volume x density','knee_twin_housing_release_r116.step vs knee_twin_housing.step','addition at full'))
so=VOL['standoff_r14']*RHO
adj.append(('stand-off R14: CAD %.4f/side vs 0.124 CALC booked'%so,0.0,'CAD-volume x density (HELD)','arms/cad/r14/standoff_r14.step','-%.3f pair held until Arms confirms STEP = drawing incl. dowel holes'%(2*(0.124-so))))
lev=VOL['hip_pitch_lever_r031_mw_b30_d36_RC']*RHO
adj.append(('hip lever L47: CAD %.4f/lever (7075) vs 0.4642 booked "measured"'%lev,0.0,'CAD-volume x density (HELD)','actuators/cad/hip_pitch_lever_r031_mw_b30_d36_RC.step','-%.3f pair held: booked body may include steel bush/pins; Legs+Actuators name the body'%(2*(0.4642-lev))))
pal=VOL['palm_7075']*RHO
adj.append(('palm 7075: CAD %.4f/hand reconciles with palm_7075.json and R-037 credit'%pal,0.0,'CAD-volume x density','arms/cad/palm_7075.step','confirmed, no change'))
fb=fa['st']/1000
adj.append(('actuator fasteners: BOM %.3f kg (1234 pcs) vs booked 0.302+0.517+0.390+0.875=2.084'%fb,round(fb-2.084,3),'counted BOM','actuators/results/fastener_bom.json','confirmed, no double count with arms FASTENER_BOM after R-125 -0.107'))
for l,kg,tag,src,note in adj: add('G4 check',l,kg,tag,src,note)
g4=sum(x['kg'] for x in L)
out=dict(ledger_chain_kg=round(ledger,3),g4_credible_kg=round(g4,3),limit=66.5,reserve_target=0.30,
         reserve_vs_66p5=round(66.5-g4,3),needed_for_reserve=round(g4-66.2,3),lines=L,
         candidate_double_counts=[
          dict(item='v3 actuator() unlabelled +0.04 per rotary unit (18 units in arms/waist/hip)',kg_upper=0.72,status='owners to state content; possible overlap with harness connectors 0.261 and cad_mass connector allowances'),
          dict(item='v3 linear unit +0.08 +0.10 per motor side (knee/ankle x2 legs)',kg_upper=2.16,status='Actuators to state whether cad_mass/linkage table (R-015) removed these; if not, part may be double counted with CAD linkage 0.609/1.086'),
          dict(item='cad_mass connector allowance 0.015 rotary / 0.010 linear vs harness connectors',kg_upper=0.18,status='Electronics/Actuators')],
         stale=['MASS_ROLLUP_OFFICIAL.md at 65.809 (R-031) -> regenerated by R-126',
                'v3 DRIVE mass is Novanta Everest 0.038 placeholder; selected drive is Elmo Gold Twitter (R-006) - mass not cited',
                'R-123 (c) quotes leg housings 2.221 kg; cad_mass per_leg housing 1.657 x2 = %.3f (knee twin both halves) - basis differs'%(2*cm['per_leg']['housing'])])
json.dump(out,open(R+'arbiter/mass_rollup_g4.json','w'),indent=1)
print(json.dumps({k:v for k,v in out.items() if k!='lines'},indent=1))
for x in L: print(f"{x['kg']:8.3f}  {x['module']:12s} {x['line'][:90]}")
