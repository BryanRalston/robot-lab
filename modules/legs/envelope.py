"""Requirement envelope across scenarios (from results/*.npz written by scenarios.py) vs CONTRACTS.md rev 0 §1a. Writes results/envelope.json, results/requirements.md."""
import json,numpy as np,os
from gait_lib import LEG,HERE,DT
import plots
OUT=os.path.join(HERE,'results')
SCN=['walk_1p2','walk_1p0','walk_0p8','stairs_18cm','carry_20kg','sit_to_stand','push_recover']
# CONTRACTS.md rev 0 §1a: need peak (=1.5 x req), v3 available peak, need speed [EST v2], v3 available speed
C={'hip_yaw':(24.0,36,3,5.3),'hip_roll':(122.1,167,3,4.9),'hip_pitch':(114.8,167,4,4.9),'knee':(231.9,238,8,12.1),'ankle_pitch':(153.2,284,6,10.1),'ankle_roll':(57.5,163,4,17.7)}
contract={j:dict(need=c[0],req=c[0]/1.5,avail=c[1],speed=c[2],avail_speed=c[3]) for j,c in C.items()}
def met(name):
    d=np.load(f'{OUT}/{name}.npz'); T=d['TAU'].astype(float); V=d['V'].astype(float); va=d['va']; info=json.load(open(f'{OUT}/{name}.json'))
    o={}
    for i,j in enumerate(LEG):
        r=[]
        for off in (0,6):
            t=T[:,va[i+off]]; w=V[:,va[i+off]]; p=t*w; pk=np.abs(t).max()
            r.append(dict(peak_Nm=pk,p99_Nm=np.percentile(np.abs(t),99),rms_Nm=np.sqrt(np.mean(t*t)),peak_rads=np.abs(w).max(),
                speed_at30_rads=np.abs(w[np.abs(t)>=0.3*pk]).max() if pk>0 else 0,peak_W=np.abs(p).max(),mean_abs_W=np.mean(np.abs(p)),
                duty50=np.mean(np.abs(t)>=0.5*pk),peak_no_arm_Nm=info['metrics'][j]['peak_Nm_no_armature']))
        o[j]={k:float(max(a[k] for a in r)) for k in r[0]}
    return o,info['info']
M={};I={}
for s in SCN: M[s],I[s]=met(s)
keys=['peak_Nm','p99_Nm','rms_Nm','peak_rads','speed_at30_rads','peak_W','mean_abs_W','duty50']
env={}
for j in LEG:
    env[j]={}
    for k in keys:
        s=max(SCN,key=lambda s:M[s][j][k]); env[j][k]=dict(value=M[s][j][k],scenario=s)
json.dump(dict(per_scenario=M,info=I,envelope=env,contract_rev0=contract),open(f'{OUT}/envelope.json','w'),indent=1)
plots.envelope(env,contract)
L=['# Leg joint requirements from gait inverse dynamics (one side, worst of L/R)\n','Generated by `modules/legs/envelope.py` from `results/*.npz`. Torque is joint-output torque incl. reflected rotor inertia (armature). Duty = fraction of the scenario time with |τ| ≥ 50 % of that scenario\'s peak.\n']
L.append('\n## Envelope (governing scenario in brackets)\n\n| joint | peak τ N·m | p99 τ N·m | RMS τ N·m | peak ω rad/s | ω at ≥30 % peak τ | peak |P| W | mean |P| W | duty |\n|---|---|---|---|---|---|---|---|---|\n')
for j in LEG:
    e=env[j]; L.append(f"| {j} | "+" | ".join(f"{e[k]['value']:.{2 if k in('peak_rads','speed_at30_rads','duty50') else 0}f} [{e[k]['scenario']}]" for k in keys)+" |\n")
L.append('\n## vs CONTRACTS.md rev 0 §1a\n\n| joint | v3 req (need/1.5) | gait-ID peak | ratio | proposed need = 1.5 × peak | v3 avail | v3 need speed [EST v2] | gait-ID peak ω | v3 avail ω |\n|---|---|---|---|---|---|---|---|---|\n')
for j in LEG:
    c=contract[j]; p=env[j]['peak_Nm']['value']; w=env[j]['peak_rads']['value']
    L.append(f"| {j} | {c['req']:.1f} | {p:.1f} | {p/c['req']:.2f} | {1.5*p:.0f} | {c['avail']} | {c['speed']} | {w:.2f} | {c['avail_speed']} |\n")
for s in SCN:
    L.append(f'\n## {s}\n\nchecks: ' + json.dumps({k:I[s][k] for k in ('mass_kg','duration_s','cop_inside_sole','base_residual_max','base_residual_p99_N','frames_residual_gt_5pctBW','max_vertical_GRF_BW','max_friction_ratio') if k in I[s]})+'\n\n| joint | peak τ | p99 τ | RMS τ | peak ω | ω@30% | peak |P| | duty | peak τ w/o armature | ROM used deg |\n|---|---|---|---|---|---|---|---|---|---|\n')
    jm=json.load(open(f'{OUT}/{s}.json'))['metrics']
    for j in LEG:
        m=M[s][j]; L.append(f"| {j} | {m['peak_Nm']:.1f} | {m['p99_Nm']:.1f} | {m['rms_Nm']:.1f} | {m['peak_rads']:.2f} | {m['speed_at30_rads']:.2f} | {m['peak_W']:.0f} | {m['duty50']:.2f} | {m['peak_no_arm_Nm']:.1f} | {jm[j]['qmin_deg']:.0f} … {jm[j]['qmax_deg']:.0f} |\n")
open(f'{OUT}/requirements.md','w').write(''.join(L)); print(''.join(L[:20]))
