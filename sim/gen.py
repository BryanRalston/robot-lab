# Generates humanoid.xml from design-spec values (masses [EST] from mass budget, limits/torques from joint table §3)
import math
D=math.radians
def j(name,axis,lo,hi,arm=0.05,damp=1.0): return f'<joint name="{name}" axis="{axis}" range="{lo} {hi}" armature="{arm}" damping="{damp}"/>'
acts=[]
def A(name,tau): acts.append(f'<motor name="{name}" joint="{name}" ctrlrange="-{tau} {tau}" ctrllimited="true"/>')
def leg(s,y):
    sg=1 if s=='l' else -1
    A(f'{s}_hip_yaw',150);A(f'{s}_hip_roll',300);A(f'{s}_hip_pitch',400);A(f'{s}_knee',450);A(f'{s}_ankle_pitch',250);A(f'{s}_ankle_roll',120);A(f'{s}_toe',40)
    rl,rh=(-30,90) if s=='l' else (-90,30)
    return f'''
    <body name="{s}_hip" pos="0 {y} -0.05">
      {j(f"{s}_hip_yaw","0 0 1",-45,45,0.1)}{j(f"{s}_hip_roll","1 0 0",rl,rh,0.1)}{j(f"{s}_hip_pitch","0 1 0",-160,45,0.15)}
      <geom name="{s}_thigh" type="capsule" fromto="0 0 0 0 0 -0.42" size="0.065" mass="7.0"/>
      <body name="{s}_shank" pos="0 0 -0.42">
        {j(f"{s}_knee","0 1 0",0,165,0.15)}
        <geom name="{s}_shank" type="capsule" fromto="0 0 0 0 0 -0.40" size="0.05" mass="3.5"/>
        <body name="{s}_foot" pos="0 0 -0.44">
          {j(f"{s}_ankle_pitch","0 1 0",-50,50,0.05)}{j(f"{s}_ankle_roll","1 0 0",-30,30,0.05)}
          <geom name="{s}_foot" type="box" pos="0.03 0 -0.02" size="0.1 0.05 0.02" mass="1.2" friction="1.0"/>
          <site name="{s}_foot_site" pos="0.03 0 -0.04"/>
          <body name="{s}_toe" pos="0.13 0 -0.02">
            {j(f"{s}_toe","0 1 0",-60,0,0.01)}
            <geom name="{s}_toe" type="box" pos="0.03 0 0" size="0.03 0.05 0.02" mass="0.3" friction="1.0"/>
          </body>
        </body>
      </body>
    </body>'''
def arm(s,y):
    A(f'{s}_shoulder_pitch',180);A(f'{s}_shoulder_roll',150);A(f'{s}_shoulder_yaw',80);A(f'{s}_elbow',150);A(f'{s}_wrist_roll',25);A(f'{s}_wrist_pitch',30);A(f'{s}_wrist_yaw',30)
    rl,rh=(-20,190) if s=='l' else (-190,20)
    return f'''
      <body name="{s}_upper_arm" pos="0 {y} 0.2">
        {j(f"{s}_shoulder_pitch","0 1 0",-180,180,0.08)}{j(f"{s}_shoulder_roll","1 0 0",rl,rh,0.08)}{j(f"{s}_shoulder_yaw","0 0 1",-170,170,0.05)}
        <geom name="{s}_upper_arm" type="capsule" fromto="0 0 0 0 0 -0.29" size="0.045" mass="3.0"/>
        <body name="{s}_forearm" pos="0 0 -0.29">
          {j(f"{s}_elbow","0 1 0",-150,0,0.05)}
          <geom name="{s}_forearm" type="capsule" fromto="0 0 0 0 0 -0.27" size="0.04" mass="2.5"/>
          <body name="{s}_hand" pos="0 0 -0.27">
            {j(f"{s}_wrist_roll","0 0 1",-180,180,0.01)}{j(f"{s}_wrist_pitch","0 1 0",-80,80,0.01)}{j(f"{s}_wrist_yaw","1 0 0",-40,40,0.01)}
            <geom name="{s}_hand" type="box" pos="0 0 -0.09" size="0.025 0.045 0.09" mass="1.1"/>
          </body>
        </body>
      </body>'''
L=leg('l',0.1);R=leg('r',-0.1)
A('waist_yaw',250);A('waist_pitch',400);A('waist_roll',250)
AL=arm('l',0.21);AR=arm('r',-0.21)
A('neck_yaw',10);A('neck_pitch',10)
xml=f'''<mujoco model="humanoid_v1">
  <!-- Generated by gen.py from humanoid_plan_v1.md. Masses = mass-budget estimates [EST]; joint ranges and motor torque limits = joint table §3 [EST].
       Hands are rigid 1.1 kg bodies (21-DoF hand not modeled yet). Inertias computed from geom shapes with given masses. -->
  <compiler angle="degree" autolimits="true"/>
  <option timestep="0.002" integrator="implicitfast"/>
  <visual><global offwidth="1280" offheight="720"/></visual>
  <default><geom contype="1" conaffinity="1" condim="3" rgba="0.5 0.7 0.88 1"/></default>
  <asset><texture name="grid" type="2d" builtin="checker" rgb1=".1 .15 .2" rgb2=".15 .2 .25" width="300" height="300"/><material name="grid" texture="grid" texrepeat="8 8"/></asset>
  <worldbody>
    <light pos="0 0 4" dir="0 0 -1"/>
    <geom name="floor" type="plane" size="10 10 0.1" material="grid"/>
    <body name="pelvis" pos="0 0 0.952">
      <freejoint name="root"/>
      <site name="imu" pos="0 0 0"/>
      <geom name="pelvis" type="box" size="0.09 0.15 0.06" mass="8.0"/>
      {L}{R}
      <body name="torso" pos="0 0 0.1">
        {j("waist_yaw","0 0 1",-180,180,0.1)}{j("waist_pitch","0 1 0",-60,60,0.1)}{j("waist_roll","1 0 0",-30,30,0.1)}
        <geom name="torso" type="box" pos="0 0 0.22" size="0.11 0.17 0.22" mass="20.0"/>
        {AL}{AR}
        <body name="head" pos="0 0 0.5">
          {j("neck_yaw","0 0 1",-180,180,0.01)}{j("neck_pitch","0 1 0",-50,50,0.01)}
          <geom name="head" type="sphere" pos="0 0 0.11" size="0.1" mass="2.5"/>
        </body>
      </body>
    </body>
  </worldbody>
  <contact><exclude body1="pelvis" body2="l_hip"/><exclude body1="pelvis" body2="r_hip"/><exclude body1="pelvis" body2="torso"/></contact>
  <actuator>
    {chr(10).join("    "+a for a in acts)}
  </actuator>
  <sensor><accelerometer name="imu_acc" site="imu"/><gyro name="imu_gyro" site="imu"/><force name="l_foot_f" site="l_foot_site"/><force name="r_foot_f" site="r_foot_site"/></sensor>
</mujoco>'''
open('humanoid.xml','w').write(xml)
print(len(acts),'actuators')
