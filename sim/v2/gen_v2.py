"""MJCF for Robot Lab v2, generated from v2/analysis (design.py + results/summary_final.json).
Masses/torque limits come from the checked design; inertias computed by MuJoCo from geom shapes with given masses."""
import json,sys,math
sys.path.insert(0,'../../v2/analysis');import design as D
S=json.load(open('../../v2/analysis/results/summary_final.json'));d=D.final();seg=S['segments'];cap=S['cap']
J=d['JOINTS'];M=d['MOTORS'];GR=d['GEARS']
def am(n):
    g,k,mo,ge,lead,arm,c=J[n];return M[mo]['mass']+(GR[ge]['mass'] if ge else 0.35*(lead or 1)/4+0.25)+D.OVERHEAD_BY_MOTOR[mo]
mi=d['MASS_ITEMS']
upper_arm=mi['upper arm+forearm structure x2']/4+am('shoulder_yaw')+am('elbow')
forearm=mi['upper arm+forearm structure x2']/4+am('wrist_roll')+am('wrist_pitch')+am('wrist_yaw')+mi['hands x2 (22-DoF, actuators in forearm counted here)']/4
hand=mi['hands x2 (22-DoF, actuators in forearm counted here)']/4
head=mi['head (cameras, shell)']+am('neck_pitch')
shoulder_block=am('shoulder_pitch')+am('shoulder_roll')
torso=seg['upper']-2*(upper_arm+forearm+hand)-head-am('neck_yaw')  # includes battery, compute, waist acts, shoulder blocks
G=d['GEO']
lim={'hip_yaw':(-45,45),'hip_roll':(-30,90),'hip_pitch':(-150,40),'knee':(0,150),'ankle_pitch':(-45,40),'ankle_roll':(-25,25),
     'waist_yaw':(-90,90),'waist_pitch':(-30,60),'shoulder_pitch':(-180,60),'shoulder_roll':(-15,180),'shoulder_yaw':(-150,150),
     'elbow':(-140,0),'wrist_roll':(-170,170),'wrist_pitch':(-70,70),'wrist_yaw':(-40,40),'neck_yaw':(-80,80),'neck_pitch':(-40,40)}
acts=[]
def j(n,s,axis,arm=0.05):
    lo,hi=lim[n]
    if s=='r' and n in('hip_roll','shoulder_roll'): lo,hi=-hi,-lo
    name=f'{s}_{n}' if s else n
    acts.append(f'<motor name="{name}" joint="{name}" ctrlrange="{-cap[n]:.0f} {cap[n]:.0f}"/>')
    # reflected rotor inertia (armature) ~ J_rotor*N^2, J_rotor ESTIMATE by class
    g,k,mo,ge,lead,a,c=J[n];Jr={'M115':4e-4,'M85':1.2e-4,'M60':3e-5,'M38':4e-6}[mo]
    N=GR[ge]['N'] if ge else 2*math.pi*a/(lead/1000)
    return f'<joint name="{name}" axis="{axis}" range="{lo} {hi}" armature="{Jr*N*N:.3f}" damping="0.5" frictionloss="0.3"/>'
def leg(s,y):
    return f'''<body name="{s}_hip" pos="0 {y} -0.04">{j('hip_yaw',s,'0 0 1')}{j('hip_roll',s,'1 0 0')}{j('hip_pitch',s,'0 1 0')}
      <geom name="{s}_thigh" type="capsule" fromto="0 0 0 0 0 -{G['thigh']}" size="0.06" mass="{seg['thigh']+0.5*(am('hip_yaw')+am('hip_roll')+am('hip_pitch')):.3f}"/>
      <body name="{s}_shank" pos="0 0 -{G['thigh']}">{j('knee',s,'0 1 0')}
        <geom name="{s}_shank" type="capsule" fromto="0 0 0 0 0 -{G['shank']}" size="0.05" mass="{seg['shank']:.3f}"/>
        <body name="{s}_foot" pos="0 0 -{G['shank']}">{j('ankle_pitch',s,'0 1 0')}{j('ankle_roll',s,'1 0 0')}
          <geom name="{s}_foot" type="box" pos="{G['foot_len']/2-G['heel']:.3f} 0 -{G['ankle_h']-0.02:.3f}" size="{G['foot_len']/2:.3f} 0.05 0.02" mass="{seg['foot']:.3f}" friction="1.0"/>
        </body></body></body>'''
def arm(s,y):
    return f'''<body name="{s}_upper_arm" pos="0 {y} {G['pelvis_to_shoulder']-0.06}">{j('shoulder_pitch',s,'0 1 0')}{j('shoulder_roll',s,'1 0 0')}{j('shoulder_yaw',s,'0 0 1')}
        <geom name="{s}_upper_arm" type="capsule" fromto="0 0 0 0 0 -{G['upper_arm']}" size="0.045" mass="{upper_arm:.3f}"/>
        <body name="{s}_forearm" pos="0 0 -{G['upper_arm']}">{j('elbow',s,'0 1 0')}
          <geom name="{s}_forearm" type="capsule" fromto="0 0 0 0 0 -{G['forearm']}" size="0.04" mass="{forearm:.3f}"/>
          <body name="{s}_hand" pos="0 0 -{G['forearm']}">{j('wrist_roll',s,'0 0 1')}{j('wrist_pitch',s,'0 1 0')}{j('wrist_yaw',s,'1 0 0')}
            <geom name="{s}_hand" type="box" pos="0 0 -0.08" size="0.02 0.045 0.08" mass="{hand:.3f}"/>
          </body></body></body>'''
z0=G['ankle_h']+G['shank']+G['thigh']+0.04
body=f'''<body name="pelvis" pos="0 0 {z0:.3f}"><freejoint name="root"/><site name="imu"/>
    <geom name="pelvis" type="box" size="0.08 0.14 0.06" mass="{seg['pelvis']-(am('hip_yaw')+am('hip_roll')+am('hip_pitch')):.3f}"/>
    {leg('l',G['hip_w']/2)}{leg('r',-G['hip_w']/2)}
    <body name="torso" pos="0 0 0.08">{j('waist_yaw','','0 0 1')}{j('waist_pitch','','0 1 0')}
      <geom name="torso" type="box" pos="0.0 0 0.24" size="0.11 0.17 0.24" mass="{torso:.3f}"/>
      {arm('l',0.22)}{arm('r',-0.22)}
      <body name="head" pos="0 0 {G['pelvis_to_shoulder']+0.02}">{j('neck_yaw','','0 0 1')}{j('neck_pitch','','0 1 0')}
        <geom name="head" type="sphere" pos="0 0 0.11" size="0.1" mass="{head:.3f}"/></body>
    </body></body>'''
xml=f'''<mujoco model="robotlab_v2">
  <!-- Generated by gen_v2.py from v2/analysis. Torque limits = checked actuator peak capacity; masses = v2 mass budget (ESTIMATES).
       Hands are rigid; linear actuators modeled as equivalent rotary joints with reflected inertia. Hip actuator mass split 50/50 between pelvis and thighs. -->
  <compiler angle="degree" autolimits="true"/>
  <option timestep="0.002" integrator="implicitfast"/>
  <default><geom contype="1" conaffinity="1" condim="3" rgba="0.5 0.7 0.88 1"/></default>
  <asset><texture name="grid" type="2d" builtin="checker" rgb1=".1 .15 .2" rgb2=".15 .2 .25" width="300" height="300"/><material name="grid" texture="grid" texrepeat="8 8"/></asset>
  <worldbody><light pos="0 0 4" dir="0 0 -1"/><geom name="floor" type="plane" size="20 20 0.1" material="grid"/>
  {body}
  </worldbody>
  <contact><exclude body1="pelvis" body2="l_hip"/><exclude body1="pelvis" body2="r_hip"/><exclude body1="pelvis" body2="torso"/><exclude body1="torso" body2="l_upper_arm"/><exclude body1="torso" body2="r_upper_arm"/></contact>
  <actuator>{"".join(acts)}</actuator>
</mujoco>'''
open('humanoid_v2.xml','w').write(xml);print('actuators',len(acts),'torso %.1f upper_arm %.2f forearm %.2f'%(torso,upper_arm,forearm))
